export function makePersonName(rng, country, used) {
  const p = POOL[country] || POOL.en;
  for (let i = 0; i < 40; i++) {
    const n = `${p.i[rng.int(p.i.length)]}. ${p.a[rng.int(p.a.length)]}${p.b[rng.int(p.b.length)]}`;
    if (!used || !used.has(n)) { if (used) used.add(n); return n; }
  }
  return `${p.i[rng.int(p.i.length)]}. ${p.a[rng.int(p.a.length)]}${p.b[rng.int(p.b.length)]}`;
}
