/* rng(makeRng 결과)로 이름 하나. used(Set)를 주면 같은 팀 안 중복도 피함 */
export function makeName(rng, used) {
  for (let i = 0; i < 50; i++) {
    const name = SURNAMES[rng.int(SURNAMES.length)] + GIVEN1[rng.int(GIVEN1.length)] + GIVEN2[rng.int(GIVEN2.length)];
    if (BLOCKED.has(name) || (used && used.has(name))) continue;
    if (used) used.add(name);
    return name;
  }
  return "무명" + rng.int(1000);   // 사실상 도달하지 않음
}
